def find_freecad_app() -> str:
    """Find FreeCAD application on macOS."""
    candidates = [
        "/Applications/FreeCAD.app",
        "/Applications/FreeCAD_0.21.app",
        "/Applications/FreeCAD_0.22.app",
        "/Applications/FreeCAD_weekly.app",
        os.path.expanduser("~/Applications/FreeCAD.app"),
    ]
    for path in candidates:
        if os.path.exists(path):
            return path
    return ""


def wrap_code_as_macro(code: str, part_name: str = "AI_Model") -> str:
    """
    Wrap the generated code into a complete FreeCAD macro
    that creates a document, runs the code, and saves the result.
    """
    save_path = os.path.join(OUTPUT_DIR, f"{part_name}.FCStd")
    step_path = os.path.join(OUTPUT_DIR, f"{part_name}.step")

    macro = f'''# ══════════════════════════════════════════════════════
# FreeCAD Macro — Auto-Generated by AI Model Generator
# ══════════════════════════════════════════════════════
#
# To run:
#   1. Open FreeCAD
#   2. Macro → Execute Macro → select this file
#   OR
#   3. Paste into FreeCAD Python Console (View → Panels → Python Console)
#

import FreeCAD
import Part

# ── Create document ──
doc = FreeCAD.newDocument("{part_name}")

# ── Helpers ──
Vector = FreeCAD.Vector
Placement = FreeCAD.Placement
Rotation = FreeCAD.Rotation

def update():
    doc.recompute()

def save(filepath=None):
    if filepath:
        doc.saveAs(filepath)

# ══════════════════════════════════════════
# YOUR 3D MODEL
# ══════════════════════════════════════════

{code}

# ══════════════════════════════════════════
# SAVE FILES
# ══════════════════════════════════════════

import os
os.makedirs(r"{OUTPUT_DIR}", exist_ok=True)

# Save FreeCAD native
doc.saveAs(r"{save_path}")
print(f"Saved: {save_path}")

# Save STEP file
try:
    __objs__ = []
    for obj in doc.Objects:
        if hasattr(obj, "Shape") and hasattr(obj, "Visibility"):
            if obj.Visibility:
                __objs__.append(obj)
    if not __objs__:
        __objs__ = [o for o in doc.Objects if hasattr(o, "Shape")]
    if __objs__:
        Part.export(__objs__, r"{step_path}")
        print(f"Saved STEP: {step_path}")
except Exception as e:
    print(f"STEP export skipped: {{e}}")

# Fit view
try:
    import FreeCADGui
    FreeCADGui.ActiveDocument.ActiveView.fitAll()
except Exception:
    pass

print("\\n🎉 Model created successfully!")
'''
    return macro


def save_macro_file(code: str, name: str) -> tuple:
    """Save code as .FCMacro and .py files. Returns (macro_path, py_path)."""
    # Clean name
    safe = "".join(c if c.isalnum() or c in "-_ " else "_" for c in name)
    safe = safe.strip().replace(" ", "_")[:40] or "Model"

    macro_content = wrap_code_as_macro(code, safe)

    macro_path = os.path.join(OUTPUT_DIR, f"{safe}.FCMacro")
    py_path = os.path.join(OUTPUT_DIR, f"{safe}.py")

    with open(macro_path, "w") as f:
        f.write(macro_content)

    with open(py_path, "w") as f:
        f.write(macro_content)

    return macro_path, py_path


def open_in_freecad(macro_path: str) -> bool:
    """Open macro file in FreeCAD."""
    app = find_freecad_app()
    if app:
        try:
            subprocess.Popen(["open", "-a", app, macro_path])
            return True
        except Exception:
            pass

    # Fallback: try generic open
    try:
        subprocess.Popen(["open", macro_path])
        return True
    except Exception:
        return False


def run_in_freecad_headless(py_path: str) -> bool:
    """Run script using FreeCAD's command-line mode."""
    app = find_freecad_app()
    if not app:
        return False

    # Try FreeCADCmd (headless mode)
    cmd_paths = [
        os.path.join(app, "Contents/Resources/bin/FreeCADCmd"),
        os.path.join(app, "Contents/bin/FreeCADCmd"),
        os.path.join(app, "Contents/MacOS/FreeCADCmd"),
        "FreeCADCmd",
    ]

    for cmd in cmd_paths:
        if os.path.exists(cmd) or cmd == "FreeCADCmd":
            try:
                print(f"{Y}Running headless: {cmd}{X}")
                result = subprocess.run(
                    [cmd, "--console", "--run", py_path],
                    capture_output=True,
                    text=True,
                    timeout=30,
                )
                print(result.stdout)
                if result.stderr:
                    print(f"{Y}{result.stderr}{X}")
                return result.returncode == 0
            except (FileNotFoundError, subprocess.TimeoutExpired):
                continue
    return False


